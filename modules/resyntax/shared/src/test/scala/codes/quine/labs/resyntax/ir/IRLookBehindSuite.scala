package codes.quine.labs.resyntax.ir

import codes.quine.labs.resyntax.ast.Dialect
import codes.quine.labs.resyntax.ast.Dialect.*
import codes.quine.labs.resyntax.ast.PerlSource

/** IRLookBehindSuite is tests of look-behind restrictions, where each case is checked with the engines. */
class IRLookBehindSuite extends IRSuiteBase:
  def valid(s: String, dialects: Dialect*)(implicit loc: munit.Location): Unit =
    for dialect <- dialects do
      test(s"IRBuilder.build: /$s/ in $dialect is valid"):
        build(s, "", dialect)

  // .NET and JavaScript accept every look-behind.
  valid("(?<=a+)", DotNet, JavaScript)
  valid("(?<=(a)\\1)", DotNet, JavaScript)
  valid("(?<=a*b+|(?:ab)*)", DotNet, JavaScript)

  // Python requires a fixed width.
  valid("(?<=a|b)", Python())
  valid("(?<=a{255})", Python())
  valid("(?<=a{65535}b)", Python())
  valid("(?<=(?:ab|cd){2})", Python())
  valid("(a)(?<=(?(1)a|b))", Python())
  error("(a)(?<=(?(1)a|bc))", "", Python())("Look-behind requires fixed-width pattern at 3")
  valid("(a)(?<=\\1)", Python())
  valid("(?<=(?=ab+)a)", Python())
  valid("(?<=(?!a+)b)", Python())
  valid("(?<!(a))", Python())
  valid("(?<=\\ba$)", Python())
  error("(?<=a|bc)", "", Python())("Look-behind requires fixed-width pattern at 0")
  error("(?<=a+)", "", Python())("Look-behind requires fixed-width pattern at 0")
  error("(?<=a?)", "", Python())("Look-behind requires fixed-width pattern at 0")
  error("(?<=a{1,3})", "", Python())("Look-behind requires fixed-width pattern at 0")
  error("(?<=(?>a|bc))", "", Python())("Look-behind requires fixed-width pattern at 0")
  error("(a|bc)(?<=\\1)", "", Python())("Look-behind requires fixed-width pattern at 6")
  error("(a+)(?<=\\1)", "", Python())("Look-behind requires fixed-width pattern at 4")

  // Perl requires the length to be at most 255, where a back-reference is unbounded.
  valid("(?<=a|bc)", Perl())
  valid("(?<=a(?:b|cd))", Perl())
  valid("(?<=a{1,3})", Perl())
  valid("(?<=a?)", Perl())
  valid("(?<=a{0,255})", Perl())
  valid("(?<=a{255})", Perl())
  valid("(?<=ab{0,254})", Perl())
  valid("(?<=a{0,200}a{0,55})", Perl())
  valid("(?<=(?:a{100}b?){2})", Perl())
  valid("(?<=(?=ab+)a)", Perl())
  valid("(?<=\\R)", Perl())
  error("(?<=a+)", "", Perl())("Look-behind longer than 255 at 0")
  error("(?<=a*)", "", Perl())("Look-behind longer than 255 at 0")
  error("(?<=a{0,256})", "", Perl())("Look-behind longer than 255 at 0")
  error("(?<=a{256})", "", Perl())("Look-behind longer than 255 at 0")
  error("(?<=ab{0,255})", "", Perl())("Look-behind longer than 255 at 0")
  error("(?<=a{0,200}a{0,56})", "", Perl())("Look-behind longer than 255 at 0")
  error("(?<=a{300}|b)", "", Perl())("Look-behind longer than 255 at 0")
  error("(?<=(a)\\1)", "", Perl())("Look-behind longer than 255 at 0")
  error("(a)(?<=\\1)", "", Perl())("Look-behind longer than 255 at 3")
  // Perl counts the folding on compiling the pattern, by whether the pattern itself is UTF-8 (checked against Perl 5.44).
  valid("(?i)(?<=(?:\\xDF){255})", Perl(), Perl(utf8 = false))
  error("(?i)(?<=(?:\\xDF){128})", "", Perl(source = PerlSource.String))("Look-behind longer than 255 at 4")
  error("(?i)(?<=(?:\\xDF){128})é", "", Perl())("Look-behind longer than 255 at 4")
  error("(?i)(?<=(?:\\xDF){128})\\x{100}", "", Perl(), Perl(utf8 = false))("Look-behind longer than 255 at 4")
  error("(?<=\\X)", "", Perl())("Look-behind longer than 255 at 0")
  error("(?<=(?<=a+)b)", "", Perl())("Look-behind longer than 255 at 4")
  error("(?(?<=a+)b|c)", "", Perl())("Look-behind longer than 255 at 0")
  // Perl uses the width of a called group and of the branches of a conditional.
  valid("(?<=(?1))(a)", Perl())
  valid("(a)(?<=(?1))", Perl())
  valid("(?<=(?(1)a|bc))(a)", Perl())
  error("(?<=(?R))", "", Perl())("Look-behind longer than 255 at 0")
  error("(?<x>(?<=(?1)))", "", Perl())("Look-behind longer than 255 at 5")
  error("(?<=(?(1)a{300}))(a)", "", Perl())("Look-behind longer than 255 at 0")

  // PCRE requires each top-level branch to be bounded, and at most 255 long if its length varies.
  valid("(?<=a|bc)", PCRE)
  valid("(?<=a(?:b|cd))", PCRE)
  valid("(?<=a{1,3})", PCRE)
  valid("(?<=a{0,255})", PCRE)
  valid("(?<=a{256})", PCRE)
  valid("(?<=a{65535})", PCRE)
  valid("(?<=a{300}|b)", PCRE)
  valid("(?<=(?:a{200}){2})", PCRE)
  valid("(?<=\\R)", PCRE)
  valid("(?<=(a)\\1)", PCRE)
  valid("(a)(?<=\\1)", PCRE)
  valid("(a|bc)(?<=\\1)", PCRE)
  valid("(?<=\\1)(a)", PCRE)
  error("(a(?<=\\1))", "", PCRE)("Look-behind is not limited at 2")
  error("(?<x>(?<!a\\k<x>))", "", PCRE)("Look-behind is not limited at 5")
  error("(?|(a))(?<!\\1)", "", PCRE)("Look-behind is not limited at 7")
  error("(?|(a)|(b))(?<!\\1)", "", PCRE)("Look-behind is not limited at 11")
  valid("(a)(?<!(?1))", PCRE)
  valid("(?<!(?1))(a)", PCRE)
  valid("(?<=(?(1)a{300}))(a)", PCRE)
  error("(a+)(?<!(?1))", "", PCRE)("Look-behind is not limited at 4")
  error("(?<=a+)", "", PCRE)("Look-behind is not limited at 0")
  error("(a+)(?<=\\1)", "", PCRE)("Look-behind is not limited at 4")
  error("(?<=\\X)", "", PCRE)("Look-behind is not limited at 0")
  error("(?<=(?:ab)*)", "", PCRE)("Look-behind is not limited at 0")
  error("(?<=a{0,256})", "", PCRE)("Look-behind branch is too long at 0")
  error("(?<=a{300}b?)", "", PCRE)("Look-behind branch is too long at 0")
  error("(?<=a|b{0,256})", "", PCRE)("Look-behind branch is too long at 0")
  error("(?<=a{0,200}a{0,56})", "", PCRE)("Look-behind branch is too long at 0")
  error("(?<=a{65535}b)", "", PCRE)("Look-behind is too long at 0")
  error("(?<*a+)", "", PCRE)("Look-behind is not limited at 0")
  // PCRE takes an unbounded repeat of a zero-width node as unbounded, except a look-ahead.
  valid("(?<=(?=a)*)", PCRE)
  valid("(?<=(?:){0,256})", PCRE)
  valid("(?<=(?<!.){2})", PCRE)
  error("(?<=(?:)*)", "", PCRE)("Look-behind is not limited at 0")
  error("(?<=(?<!.)*)", "", PCRE)("Look-behind is not limited at 0")
  error("(?<=(?<x>$)+)", "", PCRE)("Look-behind is not limited at 0")
  valid("(?<=(?:)*)", Perl(), Python(), Java)
  error("(?(?<=a+)b|c)", "", PCRE)("Look-behind is not limited at 0")

  // Ruby requires a fixed length of each top-level alternative, and forbids some nodes.
  valid("(?<=a|bc)", Ruby())
  valid("(?<=a|bc|)", Ruby())
  valid("(?<=(?:a|bc))", Ruby())
  valid("(?<=(?:(?:a|bc)))", Ruby())
  valid("(?<=a(?:b|c))", Ruby())
  valid("(?<=(?:a|b)|cd)", Ruby())
  valid("(?<=a{2})", Ruby())
  valid("(?<=(?:ab){2})", Ruby())
  valid("(?<=(?:a|b){2})", Ruby())
  valid("(?<=(a))", Ruby())
  valid("(?<=(a)|bc)", Ruby())
  valid("(?<=(?i:a))", Ruby())
  valid("(?<!(?i:a))", Ruby())
  valid("(?<=(?<=a)b)", Ruby())
  valid("(?<!(?<!a)b)", Ruby())
  valid("(?<=x(?<=a|bc))", Ruby())
  valid("(?<!a|bc)", Ruby())
  valid("(?<=\\b^a$)", Ruby())
  valid("(?<=\\A\\Ga\\K)", Ruby())
  valid("(?<=\\g<1>)(a)", Ruby())
  // Ruby counts a character folded to several characters under `i` by the folding.
  valid("(?i)(?<=x(?:ß|ab))y", Ruby())
  valid("(?<=x(?:ß|a))y", Ruby())
  valid("(?<=x(?:(?i)ß|ab))y", Ruby())
  valid("(?i)(?<=x(?:[ß]|ab))y", Ruby())
  valid("(?i)(?<=x(?:\\u00DF|ab))y", Ruby())
  valid("(?i)(?<=x(?:ﬃ|abc))y", Ruby())
  valid("(?i)(?<=x(?:[^ß]|a))y", Ruby())
  error("(?i)(?<=x(?:ß|a))y", "", Ruby())("Invalid pattern in look-behind at 4")
  error("(?<=x(?:ß|ab))y", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?i)(?<=x(?:[ßa]|a))y", "", Ruby())("Invalid pattern in look-behind at 4")
  error("(?i)(?<=x(?:[ßa]|ab))y", "", Ruby())("Invalid pattern in look-behind at 4")
  error("(?i)(?<=x(?:ss|a))y", "", Ruby())("Invalid pattern in look-behind at 4")
  error("(?i)(?<=x(?:(?-i)ß|ab))y", "", Ruby())("Invalid pattern in look-behind at 4")
  valid("(?i)(?<=x(?:İ|ab))y", Ruby())
  valid("(?i)(?<=x(?:\\u0130|ab))y", Ruby())
  error("(?i)(?<=x(?:İ|a))y", "", Ruby())("Invalid pattern in look-behind at 4")
  error("(?i)(?<=x(?:i\u0307|a))y", "", Ruby())("Invalid pattern in look-behind at 4")
  // Ruby's class matching the foldings of its characters is an alternation, which is valid only as the whole body.
  valid("(?i)(?<=[ßa])y", Ruby())
  valid("(?i)(?<=(?:[ßa]))y", Ruby())
  valid("(?i)(?<!\\p{Ll})y", Ruby())
  error("(?i)(?<=x[ßa])y", "", Ruby())("Invalid pattern in look-behind at 4")
  valid("(?i)(?<=[İa])y", Ruby())
  error("(?i)(?<=x[İa])y", "", Ruby())("Invalid pattern in look-behind at 4")
  error("(?i)(?<=[ßa]|b)y", "", Ruby())("Invalid pattern in look-behind at 4")
  error("(?i)(?<=([ßa]))y", "", Ruby())("Invalid pattern in look-behind at 4")
  error("(?i)(?<=x\\p{Ll})y", "", Ruby())("Invalid pattern in look-behind at 4")
  // Ruby's escapes of the bytes of a character are one character, unless the pattern is of bytes.
  valid("(?<=x(?:\\xC3\\xA9|a))y", Ruby())
  valid("(?i)(?<=x(?:\\xC3\\x9F|ab))y", Ruby())
  error("(?<=x(?:\\xC3\\xA9|ab))y", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?i)(?<=x(?:\\xC3\\x9F|a))y", "", Ruby())("Invalid pattern in look-behind at 4")
  test("IRBuilder.build: /(?<=x(?:\\xC3\\xA9|ab))y/n in Ruby is valid"):
    build("(?<=x(?:\\xC3\\xA9|ab))y", "n", Ruby())
  error("(?<=x(?:\\xC3\\xA9|a))y", "n", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=a(?:b|cd))", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=a|b(?:c|de))", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=(?:a|bc)|d)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=(a|bc))", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=(?i:a|bc))", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=(?i)a|bc)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=(?:a|bc){2})", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=a+)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=a?)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=a{1,3})", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=(?=a)a)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=(?!a)a)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=(?>a))", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=a(?~b))", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=a\\z)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=a\\Z)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=\\X)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<=\\R)", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(a)(?<=\\1)", "", Ruby())("Invalid pattern in look-behind at 3")
  error("(?<!(a))", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<!(?<x>a))", "", Ruby())("Invalid pattern in look-behind at 0")
  error("(?<!a|(b))", "", Ruby())("Invalid pattern in look-behind at 0")

  // Java requires "an obvious maximum length", which `Pattern` computes with `int` overflow.
  valid("(?<=a|bc)", Java)
  valid("(?<=a+)", Java)
  valid("(?<=a*)", Java)
  valid("(?<=a+?)", Java)
  valid("(?<=a++)", Java)
  valid("(?<=.*)", Java)
  valid("(?<=[ab]*)", Java)
  valid("(?<=ba+)", Java)
  valid("x(?<=a*b*)", Java)
  valid("(?<=a*|b)", Java)
  valid("(?<=(?:a)*)", Java)
  valid("(?<=(a)*)", Java)
  valid("(?<=(?>a*))", Java)
  valid("(?<=(?:ab)?)", Java)
  valid("(?<=(?:a|b){2}+)", Java)
  valid("(?<=(?=a|b)*)", Java)
  valid("(?<=(?=a*)b)", Java)
  valid("(?<=\\R)", Java)
  valid("(?<=\\X*)", Java)
  valid("(?<=(?:ab){0,1073741823})", Java)
  valid("(?<=a{0,2147483647}b)", Java)
  valid("(?<=a{0,1073741823}b{0,1073741824})", Java)
  error("(?<=(?:ab)*)", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(?<=(?:a|bc)*)", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(?<=(?>a|bc)*)", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(?<=(?:a|b){2})", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(?<=(?:a?){2})", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(?<=(?:ab){0,1073741824})", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(?<=a{0,1073741824}b{0,1073741824})", "", Java)(
    "Look-behind group does not have an obvious maximum length at 0"
  )
  error("(?<=ba+?)", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(?<=xa{0,2147483647})", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(?<=\\R*)", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(?<=(a)\\1)", "", Java)("Look-behind group does not have an obvious maximum length at 0")
  error("(a)(?<=\\1)", "", Java)("Look-behind group does not have an obvious maximum length at 3")

  /** Checks how the engine matches the first look-behind of the pattern. */
  def matching(s: String, dialects: Dialect*)(expected: IRLookBehindStarts*)(implicit loc: munit.Location): Unit =
    for dialect <- dialects do
      test(s"IRBuilder.build: the look-behind of /$s/ in $dialect"):
        def find(node: IRNode): Option[IRLookBehindMatch] = node.data match
          case IRNodeData.LookBehind(_, _, m)                                => Some(m)
          case IRNodeData.NonAtomicLookBehind(_, m)                          => Some(m)
          case IRNodeData.Conditional(IRCondition.LookBehind(_, _, m), _, _) => Some(m)
          case IRNodeData.Sequence(nodes) => nodes.iterator.flatMap(find).nextOption()
          case _                          => None
        val (pattern, _) = build(s, "", dialect)
        val expectedMatching =
          if expected.isEmpty then IRLookBehindMatch.Backward else IRLookBehindMatch.Forward(expected)
        assertEquals(find(pattern.node), Some(expectedMatching))

  import IRLookBehindStarts.Longest

  // .NET, JavaScript and Ruby match a look-behind backward, and the others forward from the starts before the position.
  matching("(?<=a|bc)", DotNet, JavaScript, Ruby())()
  matching("(?<=a|bc)", Perl())(Longest(1, 2))
  matching("(?<=a|bc)", PCRE)(Longest(1, 1), Longest(2, 2))
  matching("(?<=(?:a|bc))", PCRE)(Longest(1, 2))
  matching("(?<=ab|cd)", Python())(Longest(2, 2))
  matching("(?<=(?(1)a|bc))(a)", PCRE, Perl())(Longest(1, 2))
  matching("(?(?<=a|bc)x)", PCRE)(Longest(1, 1), Longest(2, 2))
  matching("(?<*a|bc)", PCRE)(Longest(1, 1), Longest(2, 2))
  // PCRE's length of a branch ends at `(*ACCEPT)`, and Perl tries the starts to `(*ACCEPT)` too.
  matching("(?<=a(*ACCEPT)b{0,300})", PCRE)(Longest(1, 1))
  matching("(?<=(?:a(*ACCEPT))bc)", PCRE)(Longest(3, 3))
  matching("(?<=(a(*ACCEPT)b))", PCRE)(Longest(1, 1))
  matching("(?<=(?:a(*ACCEPT))bc)", Perl())(Longest(1, 3))
  matching("(?<=(?>a(*ACCEPT))bc)", Perl())(Longest(3, 3))
  // Perl's starts are of the lengths of the literals, even where case-insensitive `ss` may match `ß`.
  matching("(?iu)(?<=ass)", Perl())(Longest(3, 3))
  // Java's starts are of the lengths of the body, where an unbounded one tries all the starts before the position.
  matching("(?<=a|bc)", Java)(Longest(1, 2))
  matching("(?<=a+)", Java)(Longest(1, Int.MaxValue))
  matching("(?<=ba*)", Java)(Longest(1, Int.MaxValue))
  matching("(?<=(?:ab)?+c)", Java)(Longest(1, 3))
  matching("(?<=\\R\\X)", Java)(Longest(2, Int.MaxValue))
